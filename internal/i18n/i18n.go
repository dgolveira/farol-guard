package i18n

import (
	"fmt"
	"os"
	"strings"
)

const (
	EN   = "en"
	PTBR = "pt-BR"
)

func Detect(flag string) string {
	v := flag
	if v == "" {
		v = firstEnv("FAROL_LANG", "LC_ALL", "LC_MESSAGES", "LANG")
	}
	if strings.HasPrefix(strings.ToLower(v), "pt") {
		return PTBR
	}
	return EN
}

func firstEnv(keys ...string) string {
	for _, k := range keys {
		if v := os.Getenv(k); v != "" {
			return v
		}
	}
	return ""
}

func T(lang, key string, args ...any) string {
	d := dict[lang]
	s, ok := d[key]
	if !ok {
		s, ok = dict[EN][key]
	}
	if !ok {
		return key
	}
	if len(args) == 0 {
		return s
	}
	return fmt.Sprintf(s, args...)
}

func Dict(lang string) map[string]string {
	out := make(map[string]string, len(dict[EN]))
	for k, v := range dict[EN] {
		out[k] = v
	}
	for k, v := range dict[lang] {
		out[k] = v
	}
	return out
}

